/** Years of passing, newest first (from `ahead` years from now back to 1970). */
export const yearsBack = (ahead = 0) => {
  const top = new Date().getFullYear() + ahead;
  return Array.from({ length: top - 1969 }, (_, i) => String(top - i));
};
